# frozen_string_literal: true

# The offline CI harness for the portable exports (PRD §17.1): a complete
# release, start to finish, from bytes this file makes up.
#
# It exists because every other export test proves one layer. The unit
# suites prove the projection and the writers against hand-authored
# fixtures; `exports:mmdb_test` proves the Go tool; `exports:from_release`
# proves the refusals. Nothing proved that the whole chain - native bytes
# in, three formats out, asset registry, manifest, checksums, and an OLD
# native client still finding its own three files in that manifest - works
# on one set of inputs in one run. That is the job here.
#
# Three properties are load-bearing and are the reason this is a fixture
# generator rather than a downloader:
#
#   * NO NETWORK, NO DATA REPO, NO SECRETS. The inputs are synthesized, the
#     source catalogue is a literal, and the export contract is the injected
#     fixture beside this file. A CI job that needed a release to exist
#     could not run on the PR that introduces the format.
#   * NOTHING CAN PUBLISH. The generation goes through Export::FromRelease,
#     which records `unknown` revisions and a dirty tree, drops a
#     NOT-PUBLISHABLE marker, and refuses to run at all under PUBLISH=1.
#     A synthetic release that could be mistaken for a real one would be a
#     far worse defect than the missing coverage this closes.
#   * THE TIMESTAMP IS FIXED. build_id is derived from the OASN header, so
#     a synthetic input with a frozen build_ts makes the entire output
#     deterministic - which is what lets the reproducibility check compare
#     payload hashes across two runs instead of comparing prose.
#
# The fixture is small (22 effective intervals) and deliberately awkward:
# a non-CIDR base range, overlays that split base ranges and overlays that
# cover no base range at all, an ASN with no org name, org names carrying a
# comma, a double quote and non-ASCII bytes, every category and every
# network role, and IPv6 outside the two prefixes the MMDB gate rejects.
# A fixture that only held tidy /24s would pass through a writer that had
# forgotten how to quote.

