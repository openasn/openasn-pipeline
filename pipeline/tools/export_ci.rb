          [ip("192.0.2.128"), ip("192.0.2.255"), 64_497,
           flags(category: "isp", role: "tier1_transit")],
          # AS64504 has no entry in the org sidecar.
          [ip("192.88.99.0"), ip("192.88.99.255"), 64_504,
