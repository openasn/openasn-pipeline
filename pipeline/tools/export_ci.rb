      def flags(category: nil, role: nil, **signals)
        value = CATEGORY_CODE.fetch(category) | (ROLE_CODE.fetch(role) << Binary::ROLE_SHIFT)
        signals.each do |name, on|
          value |= Export::Contract::ASN_SIGNAL_BITS.fetch(name) if on
        end
        value
      end

      def ip(text) = IPAddr.new(text).to_i

