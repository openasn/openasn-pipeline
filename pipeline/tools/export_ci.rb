      # every network role in the core-v1 vocabulary appears at least once,
      # so the CSV and SQLite column round-trips see the whole alphabet.
      def ipv4_base
        [
          # Not a CIDR block: 201 addresses. The MMDB writer has to split it.
          [ip("100.64.0.0"), ip("100.64.0.200"), 64_503,
